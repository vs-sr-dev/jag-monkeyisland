"""The input events the ROM replays, from an oracle's .in file.

    python tools/input_table.py            (JMI_INPUT=build/oracle/look38.in in the environment)

Writes csrc/jag/input_table.h, which csrc/jag/jag_main.c applies before the loop round each
event names, as scumm_pc's --input does (csrc/pc/pc_main.c apply_events): "FRAME move X Y",
"FRAME down L|R", "FRAME up L|R", "FRAME key ASCII", "FRAME keypad K" (0-9, * or #: through
csrc/scumm/keypad.c in the ROM as on the PC), '#' comments.  Without JMI_INPUT the table is
empty: the room runs idle.  Generated by build.bat; nobody edits it by hand.
"""
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, 'csrc', 'jag', 'input_table.h')
MOVE = re.compile(r'^\s*(\d+)\s+move\s+(-?\d+)\s+(-?\d+)\s*$')
BUTTON = re.compile(r'^\s*(\d+)\s+(down|up)\s+([LRlr])\s*$')
KEY = re.compile(r'^\s*(\d+)\s+key\s+(\d+)\s*$')
KEYPAD = re.compile(r'^\s*(\d+)\s+keypad\s+([0-9*#])\s*$')


def main():
    path = os.environ.get('JMI_INPUT', '')
    events = []
    if path:
        if not os.path.isabs(path):
            path = os.path.join(REPO, path)
        for n, line in enumerate(open(path, encoding='utf-8'), 1):
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            m = MOVE.match(line)
            if m:
                events.append((int(m.group(1)), 0, int(m.group(2)), int(m.group(3))))
                continue
            m = BUTTON.match(line)
            if m:
                kind = 1 if m.group(2) == 'down' else 2
                events.append((int(m.group(1)), kind, int(m.group(3) in 'Rr'), 0))
                continue
            m = KEY.match(line)
            if m:
                events.append((int(m.group(1)), 3, int(m.group(2)), 0))
                continue
            m = KEYPAD.match(line)
            if m:
                k = m.group(2)
                events.append((int(m.group(1)), 4, 10 if k == '*' else 11 if k == '#' else int(k), 0))
                continue
            sys.exit(f'{path}:{n}: cannot read {line!r}')
    if any(b[0] < a[0] for a, b in zip(events, events[1:])):
        sys.exit(f'{path}: the events are not in round order')
    with open(OUT, 'w', newline='\n') as f:
        f.write('/* GENERATED BY tools/input_table.py - DO NOT EDIT BY HAND. */\n')
        f.write(f'/* from: {os.environ.get("JMI_INPUT", "(none: idle)")} */\n')
        f.write('/* { round, kind (0 move, 1 down, 2 up, 3 key, 4 keypad), x / right button / ASCII / key, y } */\n')
        f.write(f'#define INPUT_EVENTS {len(events)}\n')
        f.write('static const struct { uint16_t round; uint8_t kind; int16_t a, b; } '
                'inputEvents[INPUT_EVENTS + 1] = {\n')
        for e in events:
            f.write('    { %d, %d, %d, %d },\n' % e)
        f.write('    { 0xFFFF, 0, 0, 0 }\n};\n')
    print(f'input_table: {len(events)} events' + (f' from {path}' if path else ' (idle)'))


if __name__ == '__main__':
    main()
