"""Generates csrc/scumm/opcodes_gen.h: the v4 opcode table, names and dispatch.

    python tools/gen_opcodes.py [SCUMMVM_ENGINE_DIR]   default: SCUMMVM_SRC (local.ini); without ScummVM's sources the committed
    csrc/scumm/opcodes_gen.h is kept as it is

The table is ScummVM's ScummEngine_v5::setupOpcodes with ScummEngine_v4::setupOpcodes applied
on top (its overrides and the three opcodes it disables).  An opcode whose function is defined
in csrc/scumm/ops_v5.c is dispatched to it; any other one halts the interpreter with its name.
The output is committed, so a build does not need ScummVM's source.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import localcfg  # noqa: E402
SRC = sys.argv[1] if len(sys.argv) > 1 else localcfg.get('SCUMMVM_SRC', '')


def table(path, func):
    text = open(os.path.join(SRC, path), encoding='utf-8').read()
    body = text[text.index(f'void {func}() {{'):]
    body = body[:body.index('\n}\n')]
    ops = {}
    depth = 0
    for line in body.splitlines():
        line = line.strip()
        # Opcodes set inside an `if` belong to another platform (o5_move_segafix: Sega CD).
        if line.startswith('if ('):
            depth += line.count('{')
            continue
        if depth:
            depth += line.count('{') - line.count('}')
            continue
        m = re.match(r'OPCODE\((0x[0-9a-fA-F]+),\s*(\w+)\);', line)
        if m:
            ops[int(m.group(1), 16)] = m.group(2)
        m = re.match(r'_opcodes\[(0x[0-9a-fA-F]+)\]\.setProc\(nullptr', line)
        if m:
            ops[int(m.group(1), 16)] = None
    return ops


def main():
    if not SRC or not os.path.exists(os.path.join(SRC, 'script_v5.cpp')):
        print('gen_opcodes: no ScummVM sources (SCUMMVM_SRC in local.ini): '
              'the committed csrc/scumm/opcodes_gen.h is kept')
        return
    ops = {i: None for i in range(256)}
    ops.update(table('script_v5.cpp', 'ScummEngine_v5::setupOpcodes'))
    ops.update(table('script_v4.cpp', 'ScummEngine_v4::setupOpcodes'))
    impl = set(re.findall(r'static void (o[45]_\w+)\(void\)',
                          open(os.path.join(REPO, 'csrc', 'scumm', 'ops_v5.c')).read()))
    out = ['/* SPDX-License-Identifier: GPL-2.0-or-later (generated from ScummVM\'s opcode tables) */',
           '/* GENERATED by tools/gen_opcodes.py from ScummVM\'s setupOpcodes - DO NOT EDIT. */', '',
           'const char *const opcodeNames[256] = {']
    for i in range(256):
        out.append(f'    "{ops[i] or "invalid"}",  /* {i:02X} */')
    out += ['};', '', 'void opcodes_execute(uint8_t op)', '{', '    switch (op) {']
    missing = set()
    for i in range(256):
        name = ops[i]
        if name in impl:
            out.append(f'    case 0x{i:02X}: {name}(); break;')
        elif name:
            missing.add(name)
    out += ['    default:', '        halt(opcodeNames[op]);', '    }', '}', '']
    with open(os.path.join(REPO, 'csrc', 'scumm', 'opcodes_gen.h'), 'w', newline='\n') as f:
        f.write('\n'.join(out))
    done = sorted({n for n in ops.values() if n} & impl)
    print(f'gen_opcodes: {len(done)} opcode functions implemented, {len(missing)} still missing')


if __name__ == '__main__':
    main()
